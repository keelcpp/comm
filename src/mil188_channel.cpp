ArrayRef<c64> mil188_constellation(i32 order) noexcept {
    switch (order) {
    case 16:
        return ArrayRef<c64>(kMil16, 16);
    case 32:
        return ArrayRef<c64>(kMil32, 32);
    case 64:
        return ArrayRef<c64>(kMil64, 64);
    case 256:
        return ArrayRef<c64>(kMil256, 256);
    default:
        return {};
    }
}

CommStatus mil188_qam_mod(ArrayRef<i32> symbols, i32 order, MutArrayRef<c64> out) noexcept {
    const ArrayRef<c64> table = mil188_constellation(order);
    if (table.empty() || out.size() < symbols.size()) {
        return CommStatus::kInvalidArgument;
    }
    return genqam_mod(symbols, table, out);
}

CommStatus mil188_qam_demod(ArrayRef<c64> samples, i32 order, MutArrayRef<i32> out) noexcept {
    const ArrayRef<c64> table = mil188_constellation(order);
    if (table.empty() || out.size() < samples.size()) {
        return CommStatus::kInvalidArgument;
    }
    return genqam_demod(samples, table, out);
}

f64 qfunc(f64 x) noexcept { return 0.5 * erfc(x * kInvSqrt2); }

f64 ber_awgn(f64 ebno_db, AwgnMod mod, i32 order) noexcept {
    const f64 ebno = pow(10.0, ebno_db / 10.0);
    const f64 md = as<f64>(order);
    switch (mod) {
    case AwgnMod::kPsk: {
        if (order == 2 || order == 4) {
            return 0.5 * erfc(sqrt(ebno));
        }
        const f64 k = log2(md);
        const f64 arg = sqrt(2.0 * k * ebno) * sin(kPi / md);
        return (2.0 / k) * 0.5 * erfc(arg * kInvSqrt2);
    }
    case AwgnMod::kQam: {
        const f64 k = log2(md);
        const f64 rt = sqrt(md);
        const f64 base = erfc(sqrt(3.0 * k * ebno / (2.0 * (md - 1.0))));
        return (1.0 - 1.0 / rt) * base / k;
    }
    case AwgnMod::kPam: {
        const f64 k = log2(md);
        const f64 base = erfc(sqrt(3.0 * k * ebno / (md * md - 1.0)));
        return (md - 1.0) / (md * k) * base;
    }
    case AwgnMod::kFsk:
        return 0.5 * erfc(sqrt(0.5 * ebno));
    case AwgnMod::kDpsk:
        return 0.5 * exp(-ebno);
    }
    return Limits<f64>::quiet_nan();
}

f64 noise_bw(ArrayRef<f64> num, ArrayRef<f64> den, i32 n_samp, f64 fs) noexcept {
    if (n_samp <= 0) {
        n_samp = 1024;
    }
    f64 h_max2 = 0.0;
    f64 sum_h2 = 0.0;
    const f64 nd = as<f64>(n_samp);
    for (i32 k = 0; k < n_samp; ++k) {
        const f64 w = kPi * as<f64>(k) / nd;
        const c64 z = polar(1.0, -w);
        c64 np(0.0, 0.0);
        c64 dp(0.0, 0.0);
        c64 zk(1.0, 0.0);
        for (usize i = 0; i < num.size(); ++i) {
            np += num[i] * zk;
            zk *= z;
        }
        zk = c64(1.0, 0.0);
        for (usize i = 0; i < den.size(); ++i) {
            dp += den[i] * zk;
            zk *= z;
        }
        const f64 h2 = (abs(dp) > 0.0) ? norm(np / dp) : 0.0;
        if (h2 > h_max2) {
            h_max2 = h2;
        }
        sum_h2 += h2;
    }
    return (h_max2 > 0.0) ? (fs * sum_h2 / h_max2 / nd) : 0.0;
}

